/**
 * Mobile string export (M10): turns the `mobile.*` catalogs and the shared keys into Android
 * `strings.xml`, iOS `Localizable.xcstrings` and typed Kotlin and Swift accessors. Pure: the
 * script `scripts/export-mobile.mjs` only reads the catalogs and writes the results.
 *
 *  - `{name}` becomes `%N$s` (Android) or `%N$@` (Xcode); N is the argument's first-appearance
 *    position in the English message, which German shares.
 *  - `{n, plural, …}` becomes an Android `<plurals>` (`%N$d`) or an `.xcstrings` plural variation
 *    (`%N$lld`); the plural argument is an `Int` in the accessors, every other argument a `String`.
 *  - Anything outside that subset fails the export, naming the key (see `mobileParse.ts`).
 */
import { parseMobileMessage, type ParsedMessage, type Piece, type Variant } from "./mobileParse.ts";

export { parseMobileMessage } from "./mobileParse.ts";
export type { ParsedMessage } from "./mobileParse.ts";

export type Catalog = Readonly<Record<string, string>>;
export type ExportLocale = "en" | "de";

export interface MobileEntry {
  readonly key: string;
  /** Argument names in the order the accessors take them (English first appearance). */
  readonly args: readonly string[];
  readonly plural: string | null;
  readonly messages: Readonly<Record<ExportLocale, ParsedMessage>>;
}

/** Package and `R` of the Android app (applicationId: OD-M10-1). */
export const androidPackage = "io.github.stephanbaum.mosaic";

// "--" is illegal inside an XML comment, so the command is spelled with `-F`.
const generated = "Generated by `pnpm -F @mosaic/i18n export:mobile` from packages/i18n. Do not edit.";
const reserved = new Set([
  // Kotlin and Swift keywords that cannot be parameter names, plus the generated members.
  "as", "break", "class", "continue", "default", "do", "else", "false", "for", "fun", "if", "in",
  "interface", "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try",
  "typealias", "val", "var", "when", "while", "func", "let", "self", "struct", "switch", "case",
  "enum", "import", "init", "nil", "operator", "repeat", "static", "where", "r",
]);
const reservedAccessors = new Set(["errorCodes", "errorMessage"]);

/** Android resource name: `.` becomes `_`. */
export function androidName(key: string): string {
  return key.replaceAll(".", "_");
}

/** Accessor name: the `mobile.` prefix is dropped, the rest is camel-cased (`mobile.unlock.failed` → `unlockFailed`). */
export function accessorName(key: string): string {
  const segments = key.replace(/^mobile\./, "").split(".");
  return segments
    .map((s, i) => (i === 0 ? s.charAt(0).toLowerCase() : s.charAt(0).toUpperCase()) + s.slice(1))
    .join("");
}

const mobileErrorPrefix = "mobile.error.";

/**
 * The catalog the apps export: a `mobile.error.<code>` text replaces the desktop `error.<code>` text, so the
 * phone never says "computer", "window" or "Caps Lock" (docs/MOBILE.md §2).
 */
export function withMobileErrorTexts(catalog: Catalog): Catalog {
  const out: Record<string, string> = { ...catalog };
  for (const [key, text] of Object.entries(catalog)) {
    if (key.startsWith(mobileErrorPrefix)) out[`error.${key.slice(mobileErrorPrefix.length)}`] = text;
  }
  return out;
}

/** Every `mobile.*` key of `en`, plus `shared`, sorted and unique. */
export function mobileKeys(en: Catalog, shared: readonly string[]): string[] {
  // `mobile.error.<code>` only overrides the desktop `error.<code>` (see `withMobileErrorTexts`).
  const own = Object.keys(en).filter((k) => k.startsWith("mobile.") && !k.startsWith(mobileErrorPrefix));
  return [...new Set([...own, ...shared])].sort(compare);
}

function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

function checkNames(key: string, args: readonly string[]): void {
  for (const name of args) {
    if (!/^[a-z][A-Za-z0-9]*$/.test(name) || reserved.has(name)) {
      throw new Error(`${key}: argument "${name}" cannot be a Kotlin and Swift parameter name`);
    }
  }
  const resource = androidName(key);
  if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(resource)) throw new Error(`${key}: not a valid resource name`);
  if (!key.split(".").every((s) => /^[A-Za-z][A-Za-z0-9]*$/.test(s))) {
    throw new Error(`${key}: every key segment must be letters and digits`);
  }
}

function checkParity(key: string, en: ParsedMessage, de: ParsedMessage): void {
  const same = en.args.length === de.args.length && en.args.every((a) => de.args.includes(a));
  if (!same || en.plural !== de.plural) {
    throw new Error(`${key}: DE and EN use different arguments`);
  }
}

function buildEntry(en: Catalog, de: Catalog, key: string): MobileEntry {
  const enText = en[key];
  const deText = de[key];
  if (enText === undefined || deText === undefined) {
    throw new Error(`${key}: missing in ${enText === undefined ? "EN" : "DE"}`);
  }
  const messages = { en: parseMobileMessage(key, enText), de: parseMobileMessage(key, deText) };
  checkParity(key, messages.en, messages.de);
  checkNames(key, messages.en.args);
  if (key.startsWith("error.") && (messages.en.args.length > 0 || key.split(".").length !== 2)) {
    throw new Error(`${key}: an error text takes no arguments`);
  }
  return { key, args: messages.en.args, plural: messages.en.plural, messages };
}

/** Parses and checks every key; throws on the first problem, naming the key. */
export function buildEntries(en: Catalog, de: Catalog, keys: readonly string[]): MobileEntry[] {
  const entries = keys.map((key) => buildEntry(en, de, key));
  const seen = new Map<string, string>();
  for (const { key } of entries) {
    for (const name of [`r:${androidName(key)}`, `f:${accessorName(key)}`]) {
      const other = seen.get(name);
      if (other !== undefined) throw new Error(`${key}: resource or accessor name clashes with ${other}`);
      seen.set(name, key);
    }
    if (reservedAccessors.has(accessorName(key))) throw new Error(`${key}: reserved accessor name`);
  }
  return entries;
}

// ---------------------------------------------------------------------------------------------
// Rendering

interface Syntax {
  text(s: string): string;
  arg(position: number, numeric: boolean): string;
}

function render(variant: Variant, entry: MobileEntry, syntax: Syntax): string {
  return variant.pieces
    .map((p: Piece) => {
      if (p.text !== undefined) return syntax.text(p.text);
      const name = p.arg ?? "";
      return syntax.arg(entry.args.indexOf(name) + 1, name === entry.plural);
    })
    .join("");
}

const categoryOrder = ["zero", "one", "two", "few", "many", "other"];

function orderedVariants(m: ParsedMessage): Variant[] {
  return [...m.variants].sort(
    (a, b) => categoryOrder.indexOf(a.selector) - categoryOrder.indexOf(b.selector),
  );
}

// Android -------------------------------------------------------------------------------------

/**
 * Escapes literal text for an Android string resource: `\\`, `&amp;`, `&lt;`, `\'`, `\"`, `\n`,
 * and `%` as `%%` when the resource is formatted (has arguments).
 */
export function escapeAndroidText(s: string, formatted: boolean): string {
  const out = s
    .replaceAll("\\", "\\\\")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll("'", "\\'")
    .replaceAll('"', '\\"')
    .replaceAll("\n", "\\n");
  return formatted ? out.replaceAll("%", "%%") : out;
}

function androidText(variant: Variant, entry: MobileEntry, formatted: boolean): string {
  const text = render(variant, entry, {
    text: (s) => escapeAndroidText(s, formatted),
    arg: (n, numeric) => `%${String(n)}$${numeric ? "d" : "s"}`,
  });
  // A leading "@" or "?" would be read as a resource or theme reference.
  return /^[@?]/.test(text) ? `\\${text}` : text;
}

function androidResource(entry: MobileEntry, locale: ExportLocale): string {
  const message = entry.messages[locale];
  const name = androidName(entry.key);
  if (entry.plural !== null) {
    const items = orderedVariants(message).map(
      (v) => `    <item quantity="${v.selector}">${androidText(v, entry, true)}</item>`,
    );
    return `  <plurals name="${name}">\n${items.join("\n")}\n  </plurals>`;
  }
  const variant = message.variants[0] as Variant;
  const formatted = entry.args.length > 0;
  const text = androidText(variant, entry, formatted);
  // Without arguments the string is never formatted, so a literal % stays single.
  const plainPercent = !formatted && variant.pieces.some((p) => p.text?.includes("%") === true);
  return `  <string name="${name}"${plainPercent ? ' formatted="false"' : ""}>${text}</string>`;
}

/** `res/values/strings.xml` (EN) or `res/values-de/strings.xml` (DE). */
export function androidStrings(entries: readonly MobileEntry[], locale: ExportLocale): string {
  const body = entries.map((e) => androidResource(e, locale)).join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${generated} -->\n<resources>\n${body}\n</resources>\n`;
}

// Xcode ---------------------------------------------------------------------------------------

function xcodeText(variant: Variant, entry: MobileEntry): string {
  const formatted = entry.args.length > 0;
  return render(variant, entry, {
    text: (s) => (formatted ? s.replaceAll("%", "%%") : s),
    arg: (n, numeric) => `%${String(n)}$${numeric ? "lld" : "@"}`,
  });
}

type Json = string | number | { [key: string]: Json };

function unit(value: string): Json {
  return { stringUnit: { state: "translated", value } };
}

function xcodeLocalization(entry: MobileEntry, locale: ExportLocale): Json {
  const message = entry.messages[locale];
  if (entry.plural === null) return unit(xcodeText(message.variants[0] as Variant, entry));
  const plural: Record<string, Json> = {};
  for (const v of orderedVariants(message)) plural[v.selector] = unit(xcodeText(v, entry));
  const argNum = entry.args.indexOf(entry.plural) + 1;
  const counted = Object.values(plural).some((u) => JSON.stringify(u).includes(`%${String(argNum)}$lld`));
  if (counted) return { variations: { plural } };
  // Xcode infers a plural's format specifier from the variants; when no variant shows the count
  // ("Website" / "Websites"), the count goes through a substitution that prints nothing itself.
  return {
    stringUnit: { state: "translated", value: "%#@count@" },
    substitutions: {
      count: { argNum, formatSpecifier: "lld", variations: { plural } },
    },
  };
}

function stringify(value: Json, indent: string): string {
  if (typeof value !== "object") return JSON.stringify(value);
  const inner = `${indent}  `;
  const lines = Object.keys(value)
    .sort(compare)
    .map((k) => `${inner}${JSON.stringify(k)} : ${stringify(value[k] as Json, inner)}`);
  return `{\n${lines.join(",\n")}\n${indent}}`;
}

/** `Localizable.xcstrings`, in the layout Xcode writes (sorted keys, ` : `, two spaces). */
export function xcstrings(entries: readonly MobileEntry[]): string {
  const strings: Record<string, Json> = {};
  for (const entry of entries) {
    strings[entry.key] = {
      extractionState: "manual",
      localizations: { de: xcodeLocalization(entry, "de"), en: xcodeLocalization(entry, "en") },
    };
  }
  return `${stringify({ sourceLanguage: "en", strings, version: "1.0" }, "")}\n`;
}

// Kotlin and Swift ------------------------------------------------------------------------------

function errorCodes(entries: readonly MobileEntry[]): string[] {
  return entries.filter((e) => e.key.startsWith("error.")).map((e) => e.key.slice("error.".length));
}

function kotlinAccessor(entry: MobileEntry): string {
  const params = ["r: Resources", ...entry.args.map((a) => `${a}: ${a === entry.plural ? "Int" : "String"}`)];
  const name = androidName(entry.key);
  const list = entry.args.join(", ");
  const call =
    entry.plural !== null
      ? `r.getQuantityString(R.plurals.${name}, ${entry.plural}, ${list})`
      : `r.getString(R.string.${name}${list === "" ? "" : `, ${list}`})`;
  const head = `    fun ${accessorName(entry.key)}(${params.join(", ")}): String`;
  return `${head} =\n        ${call}`;
}

/** `L10n.kt`: `object L10n { fun unlockFailed(r: Resources, attempts: Int): String … }`. */
export function kotlinL10n(entries: readonly MobileEntry[]): string {
  const codes = errorCodes(entries);
  const lines = codes.map(
    (c) => `        "${c}" -> ${accessorName(`error.${c}`)}(r)`,
  );
  return `// ${generated}
package ${androidPackage}.ui.l10n

import android.content.res.Resources
import ${androidPackage}.R

object L10n {
    /** Every \`MobileError::code()\` that has a string. */
    val errorCodes: List<String> =
        listOf(${codes.map((c) => `"${c}"`).join(", ")})

    /** The text of \`code\` (\`error.<code>\`), or null for a code this build does not know. */
    fun errorMessage(r: Resources, code: String): String? =
        when (code) {
${lines.join("\n")}
            else -> null
        }

${entries.map(kotlinAccessor).join("\n\n")}
}
`;
}

function swiftAccessor(entry: MobileEntry): string {
  const params = entry.args.map((a) => `${a}: ${a === entry.plural ? "Int" : "String"}`);
  const lookup = `NSLocalizedString("${entry.key}", bundle: .main, comment: "")`;
  const body =
    entry.args.length === 0
      ? lookup
      : `String(format: ${lookup}, locale: .current, arguments: [${entry.args.join(", ")}])`;
  return `    public static func ${accessorName(entry.key)}(${params.join(", ")}) -> String {\n        ${body}\n    }`;
}

/** `L10n.swift`: `enum L10n { static func unlockFailed(attempts: Int) -> String }`. */
export function swiftL10n(entries: readonly MobileEntry[]): string {
  const codes = errorCodes(entries);
  const cases = codes.map((c) => `        case "${c}": return ${accessorName(`error.${c}`)}()`);
  return `// ${generated}
import Foundation

/// Typed accessors for \`Localizable.xcstrings\`. The strings are looked up in the main bundle, so
/// the catalog must be a resource of the app and of every extension that uses \`L10n\`.
public enum L10n {
    /// Every \`MobileError::code()\` that has a string.
    public static let errorCodes: [String] = [${codes.map((c) => `"${c}"`).join(", ")}]

    /// The text of \`code\` (\`error.<code>\`), or nil for a code this build does not know.
    public static func errorMessage(code: String) -> String? {
        switch code {
${cases.join("\n")}
        default: return nil
        }
    }

${entries.map(swiftAccessor).join("\n\n")}
}
`;
}
