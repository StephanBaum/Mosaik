/**
 * Mobile token export (M10): the design tokens as Kotlin (Compose) and Swift (SwiftUI) sources.
 * Pure and deterministic; `scripts/export-mobile.mjs` writes the results. Colors become
 * `Color(0xAARRGGBB)` (Android) and `Color(.sRGB, red:…)` (iOS) from `#RRGGBB` and `rgba()`;
 * space, radius, size, border and type become `Dp`/`TextUnit` and `CGFloat`; motion is in
 * milliseconds. Light and dark sets exist for every semantic color. The shadows are hints:
 * an elevation (the y offset of the first layer) on Android, `(radius, y, opacity)` on iOS.
 * Fonts are named, not embedded; the apps bundle the TTFs of `apps/mobile/shared/fonts/`.
 */
import {
  borderWidth,
  colors,
  fontSize,
  motion,
  overlay,
  primaryAction,
  radius,
  shadow,
  shadowSubtle,
  size,
  space,
  vaultColors,
  type ColorScheme,
} from "./index.ts";

export const androidTokensPackage = "io.github.stephanbaum.mosaic.ui.theme";

const generated = "Generated by `pnpm --filter @mosaic/design-tokens export:mobile` from packages/design-tokens. Do not edit.";

export interface Argb {
  readonly a: number;
  readonly r: number;
  readonly g: number;
  readonly b: number;
}

/** Parses `#RRGGBB` or `rgba(r, g, b, a)` (a in 0 to 1) into 8-bit channels. */
export function parseColor(value: string): Argb {
  const hex = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(value);
  if (hex !== null) {
    const [r, g, b] = [hex[1], hex[2], hex[3]].map((p) => parseInt(p ?? "", 16)) as [number, number, number];
    return { a: 255, r, g, b };
  }
  const rgba = /^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)$/.exec(value);
  if (rgba !== null) {
    const [r, g, b] = [rgba[1], rgba[2], rgba[3]].map((p) => Number(p)) as [number, number, number];
    return { a: Math.round(Number(rgba[4]) * 255), r, g, b };
  }
  throw new Error(`Expected #RRGGBB or rgba(r, g, b, a), got "${value}"`);
}

/** `0xAARRGGBB`, upper case, as a Kotlin hex literal. */
export function argb(value: string): string {
  const { a, r, g, b } = parseColor(value);
  const byte = (n: number): string => n.toString(16).toUpperCase().padStart(2, "0");
  return `0x${byte(a)}${byte(r)}${byte(g)}${byte(b)}`;
}

const unit = (n: number): string => String(Number((n / 255).toFixed(6)));

/** `Color(.sRGB, red: …, green: …, blue: …, opacity: …)` with channels as fractions of 255. */
export function swiftColor(value: string): string {
  const { a, r, g, b } = parseColor(value);
  return `Color(.sRGB, red: ${unit(r)}, green: ${unit(g)}, blue: ${unit(b)}, opacity: ${unit(a)})`;
}

export interface ShadowHint {
  /** Vertical offset of the first shadow layer (px). */
  readonly y: number;
  /** Blur of the first layer (px, CSS). iOS uses half of it as its radius. */
  readonly blur: number;
  /** Alpha of the first layer's color (0 to 1). */
  readonly opacity: number;
}

/** The first layer of a CSS `box-shadow` such as `0 8px 24px rgba(9, 9, 11, 0.08), 0 1px 2px …`. */
export function shadowHint(css: string): ShadowHint {
  const m = /^(-?\d+)(?:px)?\s+(-?\d+)px\s+(\d+)px\s+rgba\(\s*\d+\s*,\s*\d+\s*,\s*\d+\s*,\s*([\d.]+)\s*\)/.exec(css);
  if (m === null) throw new Error(`Unsupported shadow "${css}"`);
  return { y: Number(m[2]), blur: Number(m[3]), opacity: Number(m[4]) };
}

type Scheme = ColorScheme & { readonly scrim: string; readonly primaryActionRim: string };

function scheme(mode: "light" | "dark"): Scheme {
  return { ...colors[mode], scrim: overlay[mode], primaryActionRim: primaryAction.rim[mode] };
}

const colorNames = (): (keyof Scheme)[] => Object.keys(scheme("light")) as (keyof Scheme)[];

const pad = (lines: string[], indent: string): string => lines.map((l) => `${indent}${l}`).join("\n");

/** Parses `cubic-bezier(a, b, c, d)`. */
function bezier(css: string): [number, number, number, number] {
  const m = /^cubic-bezier\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\)$/.exec(css);
  if (m === null) throw new Error(`Unsupported easing "${css}"`);
  return [Number(m[1]), Number(m[2]), Number(m[3]), Number(m[4])];
}

const ms = (css: string): number => parseInt(css, 10);

// Kotlin ----------------------------------------------------------------------------------------

function ktObject(name: string, type: string, values: Record<string, number>, suffix: string): string {
  const rows = Object.entries(values).map(([k, v]) => `val ${k}: ${type} = ${String(v)}.${suffix}`);
  return `object ${name} {\n${pad(rows, "    ")}\n}`;
}

function ktColors(mode: "light" | "dark"): string {
  const s = scheme(mode);
  const rows = colorNames().map((k) => `${k} = Color(${argb(s[k])}),`);
  return `val Mosaic${mode === "light" ? "Light" : "Dark"}Colors: MosaicColors =\n    MosaicColors(\n${pad(rows, "        ")}\n    )`;
}

/** `MosaicTokens.kt` for `androidTokensPackage`. */
export function kotlinTokens(): string {
  const spaceValues = Object.fromEntries(space.map((v, i) => [`s${String(i)}`, v]));
  const type = Object.entries(fontSize).map(
    ([k, { size: s, lineHeight }]) => `val ${k} = MosaicTextToken(${String(s)}.sp, ${String(lineHeight)}.sp)`,
  );
  const [x1, y1, x2, y2] = bezier(motion.easing);
  const f = (n: number): string => `${String(n)}f`;
  const popover = shadowHint(shadow.light);
  const subtle = shadowHint(shadowSubtle.light);
  return `// ${generated}
package ${androidTokensPackage}

import androidx.compose.animation.core.CubicBezierEasing
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.TextUnit
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

/** Every semantic color of one theme (UX_GUIDELINES §2), plus the modal scrim and the foil's rim. */
class MosaicColors(
${pad(colorNames().map((k) => `val ${k}: Color,`), "    ")}
)

${ktColors("light")}

${ktColors("dark")}

${ktObject("MosaicSpace", "Dp", spaceValues, "dp")}

${ktObject("MosaicRadius", "Dp", radius, "dp")}

${ktObject("MosaicSize", "Dp", size, "dp")}

${ktObject("MosaicBorderWidth", "Dp", borderWidth, "dp")}

class MosaicTextToken(val size: TextUnit, val lineHeight: TextUnit)

object MosaicType {
${pad(type, "    ")}
}

/** Font family names; the TTFs are in apps/mobile/shared/fonts (SIL OFL 1.1). */
object MosaicFonts {
    const val ui: String = "DM Sans"
    const val mono: String = "IBM Plex Mono"
}

/** Durations in milliseconds, and the standard easing. Reduced motion uses 0. */
object MosaicMotion {
    const val microMs: Int = ${String(ms(motion.micro))}
    const val panelMs: Int = ${String(ms(motion.panel))}
    val easing: CubicBezierEasing = CubicBezierEasing(${f(x1)}, ${f(y1)}, ${f(x2)}, ${f(y2)})
}

/** Elevation hints for the popover and subtle shadows (the y offset of the CSS shadow). */
object MosaicElevation {
    val popover: Dp = ${String(popover.y)}.dp
    val subtle: Dp = ${String(subtle.y)}.dp
}

/** The single primary action when the foil cannot render (no WebGL; ADR-0014). */
object MosaicPrimaryAction {
    val label: Color = Color(${argb(primaryAction.label)})
    val fallback: Color = Color(${argb(primaryAction.fallback)})
    val fallbackHighlight: Color = Color(${argb(primaryAction.fallbackHighlight)})
}

/** Vault dots. Decorative only. */
object MosaicVaultColors {
    val all: List<Color> =
        listOf(
${pad(vaultColors.map((c) => `Color(${argb(c)}),`), "            ")}
        )
}
`;
}

// Swift -----------------------------------------------------------------------------------------

function swiftEnum(name: string, values: Record<string, number>): string {
  const rows = Object.entries(values).map(([k, v]) => `public static let ${k}: CGFloat = ${String(v)}`);
  return `public enum ${name} {\n${pad(rows, "    ")}\n}`;
}

function swiftColors(mode: "light" | "dark"): string {
  const s = scheme(mode);
  const rows = colorNames().map((k) => `${k}: ${swiftColor(s[k])},`);
  return `public static let ${mode} = MosaicColors(\n${pad(rows, "    ").replace(/,$/, "")}\n)`;
}

function swiftShadow(css: string): string {
  const h = shadowHint(css);
  return `MosaicShadowToken(radius: ${String(h.blur / 2)}, y: ${String(h.y)}, opacity: ${String(h.opacity)})`;
}

/** `MosaicTokens.swift` for the `MosaicKit` framework. */
export function swiftTokens(): string {
  const spaceValues = Object.fromEntries(space.map((v, i) => [`s${String(i)}`, v]));
  const type = Object.entries(fontSize).map(
    ([k, { size: s, lineHeight }]) =>
      `public static let ${k} = MosaicTextToken(size: ${String(s)}, lineHeight: ${String(lineHeight)})`,
  );
  const colorFields = colorNames().map((k) => `public let ${k}: Color`);
  const init = colorNames().map((k) => `self.${k} = ${k}`);
  const initParams = colorNames().map((k) => `${k}: Color`).join(", ");
  return `// ${generated}
import SwiftUI

/// Every semantic color of one theme (UX_GUIDELINES §2), plus the modal scrim and the foil's rim.
public struct MosaicColors: Sendable {
${pad(colorFields, "    ")}

    public init(${initParams}) {
${pad(init, "        ")}
    }
}

public struct MosaicTextToken: Sendable {
    public let size: CGFloat
    public let lineHeight: CGFloat
}

/// Shadow as SwiftUI takes it: \`.shadow(color: .black.opacity(opacity), radius: radius, y: y)\`.
public struct MosaicShadowToken: Sendable {
    public let radius: CGFloat
    public let y: CGFloat
    public let opacity: Double
}

public enum MosaicTokens {
${pad(swiftColors("light").split("\n"), "    ")}

${pad(swiftColors("dark").split("\n"), "    ")}

    /// \`space[i]\` is the i-th step of the spacing scale.
    public static let space: [CGFloat] = [${space.map(String).join(", ")}]

${pad(swiftEnum("Space", spaceValues).split("\n"), "    ")}

${pad(swiftEnum("Radius", radius).split("\n"), "    ")}

${pad(swiftEnum("Size", size).split("\n"), "    ")}

${pad(swiftEnum("BorderWidth", borderWidth).split("\n"), "    ")}

    public enum FontSize {
${pad(type, "        ")}
    }

    /// Font family names; the TTFs are in apps/mobile/shared/fonts (SIL OFL 1.1).
    public enum Fonts {
        public static let ui = "DM Sans"
        public static let mono = "IBM Plex Mono"
    }

    /// Durations in milliseconds, and the standard easing as cubic Bezier control points.
    public enum Motion {
        public static let microMs = ${String(ms(motion.micro))}
        public static let panelMs = ${String(ms(motion.panel))}
        public static let easing: [Double] = [${bezier(motion.easing).map(String).join(", ")}]
    }

    public enum Shadow {
        public static let popoverLight = ${swiftShadow(shadow.light)}
        public static let popoverDark = ${swiftShadow(shadow.dark)}
        public static let subtleLight = ${swiftShadow(shadowSubtle.light)}
        public static let subtleDark = ${swiftShadow(shadowSubtle.dark)}
    }

    /// The single primary action when the foil cannot render (no WebGL; ADR-0014).
    public enum PrimaryAction {
        public static let label = ${swiftColor(primaryAction.label)}
        public static let fallback = ${swiftColor(primaryAction.fallback)}
        public static let fallbackHighlight = ${swiftColor(primaryAction.fallbackHighlight)}
    }

    /// Vault dots. Decorative only.
    public static let vaultColors: [Color] = [
${pad(vaultColors.map((c) => `${swiftColor(c)},`), "        ")}
    ]
}
`;
}
