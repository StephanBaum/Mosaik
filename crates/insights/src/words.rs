#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use super::*;

    #[test]
    fn words_are_lowercase_unique_and_long_enough() {
        let mut seen = HashSet::new();
        for w in COMMON_WORDS {
            assert!(w.chars().count() >= 3, "{w}");
            assert_eq!(w.to_lowercase(), *w, "{w}");
            assert!(seen.insert(*w), "duplicate {w}");
        }
    }
}
