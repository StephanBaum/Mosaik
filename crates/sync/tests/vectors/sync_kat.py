"""Independent reference for the M7 folder wire objects: the v2 account file
and the re-key marker (CRYPTO_SPEC 10.1, ADR-0058).

It shares no code with mosaic-sync or mosaic-core: HMAC and SHA-256 come from
the Python standard library and HKDF-SHA-256 is written out from RFC 5869. The
unit tests in `src/wire/kat_tests.rs` read the checked-in output
`sync_kat.txt` and compare it with the Rust encoders and decoders.

    python crates/sync/tests/vectors/sync_kat.py > crates/sync/tests/vectors/sync_kat.txt
    python crates/sync/tests/vectors/sync_kat.py --check     # exit 1 on a difference

Inputs (fixed): AK of the epoch being left = 0x11 x 32 (so `K_fold` is the
`k_fold` of `crates/core/tests/vectors/sync_kat.txt`, which `--check` also
compares); AK of the new epoch = 0x33 x 32; account ID = 0x0A x 16; device
(install) ID = 0x0E x 16; the wrapped key is 0x01 0x01 then 0x77 x 72.

- `account_file_v2_bytes`: the 172-byte `.macct` at account version 2, epoch 2,
  profile 1, salt 0x66 x 16, MAC under the K_fold of the NEW epoch (AK 0x33).
- `account_file_v1_as_epoch_1_bytes`: the 168-byte v1 file of
  `crates/core/tests/vectors/sync_kat.txt` rebuilt here (a v2 decoder reads it
  as epoch 1).
- `rekey_marker_bytes`: the 93-byte `.mrek` leaving epoch 1 for epoch 2, new
  account version 2, created at 1_700_000_200_000 ms, MAC under the K_fold of
  the epoch being LEFT (AK 0x11) with the label `sync/folder-rekey`.
- `rekey_marker_mac_under_new_epoch`: the same message MAC'd under the new
  epoch's K_fold (it must not verify as the marker's MAC).
- `k_fold_old`, `k_fold_new`: the two folder keys.
"""

import hashlib
import hmac
import os
import struct
import sys

CTX = b"mosaic/v1/"
HERE = os.path.dirname(os.path.abspath(__file__))
CORE_TXT = os.path.join(HERE, "..", "..", "..", "core", "tests", "vectors", "sync_kat.txt")
OUT_TXT = os.path.join(HERE, "sync_kat.txt")


def hkdf_sha256(ikm: bytes, salt: bytes, info: bytes, length: int) -> bytes:
    """RFC 5869 Extract-then-Expand (an empty salt means HashLen zero bytes)."""
    prk = hmac.new(salt if salt else b"\x00" * 32, ikm, hashlib.sha256).digest()
    okm, block = b"", b""
    counter = 1
    while len(okm) < length:
        block = hmac.new(prk, block + info + bytes([counter]), hashlib.sha256).digest()
        okm += block
        counter += 1
    return okm[:length]


def self_test() -> None:
    # RFC 5869 Appendix A.1.
    okm = hkdf_sha256(
        b"\x0b" * 22,
        bytes.fromhex("000102030405060708090a0b0c"),
        bytes.fromhex("f0f1f2f3f4f5f6f7f8f9"),
        42,
    )
    assert okm.hex() == (
        "3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf"
        "34007208d5b887185865"
    )


def ctx(label: str) -> bytes:
    return CTX + label.encode()


def folder_mac(k_fold: bytes, label: str, body: bytes) -> bytes:
    return hmac.new(k_fold, ctx(label) + b"\x00" + body, hashlib.sha256).digest()


def vectors() -> dict:
    self_test()
    u64 = lambda n: struct.pack(">Q", n)  # noqa: E731
    u32 = lambda n: struct.pack(">I", n)  # noqa: E731
    k_old = hkdf_sha256(b"\x11" * 32, b"", ctx("sync/folder-mac-key"), 32)
    k_new = hkdf_sha256(b"\x33" * 32, b"", ctx("sync/folder-mac-key"), 32)
    account = b"\x0a" * 16
    device = b"\x0e" * 16
    wrapped = b"\x01\x01" + b"\x77" * 72
    assert len(wrapped) == 74

    # v2 account file: magic, version 2, account, account_version, ak_epoch,
    # device, salt, profile, wrapped AK, MAC.
    v2_body = (
        b"MACC\x02" + account + u64(2) + u32(2) + device + b"\x66" * 16 + b"\x01" + wrapped
    )
    v2 = v2_body + folder_mac(k_new, "sync/folder-account", v2_body)
    assert len(v2) == 172

    # The v1 file (epoch 1, MAC under the old epoch's key).
    v1_body = b"MACC\x01" + account + u64(2) + device + b"\x66" * 16 + b"\x01" + wrapped
    v1 = v1_body + folder_mac(k_old, "sync/folder-account", v1_body)
    assert len(v1) == 168

    # Re-key marker: magic, version 1, account, from_epoch, to_epoch,
    # to_account_version, device, created_at_ms, MAC under the OLD K_fold.
    marker_body = (
        b"MREK\x01" + account + u32(1) + u32(2) + u64(2) + device + u64(1_700_000_200_000)
    )
    marker = marker_body + folder_mac(k_old, "sync/folder-rekey", marker_body)
    assert len(marker) == 93
    return {
        "k_fold_old": k_old,
        "k_fold_new": k_new,
        "account_file_v2_bytes": v2,
        "account_file_v1_as_epoch_1_bytes": v1,
        "rekey_marker_bytes": marker,
        "rekey_marker_mac_under_new_epoch": folder_mac(k_new, "sync/folder-rekey", marker_body),
    }


def render(values: dict) -> str:
    lines = ["# Generated by sync_kat.py (independent of mosaic-sync); see the script header."]
    lines += [f"{name}={value.hex()}" for name, value in values.items()]
    return "\n".join(lines) + "\n"


def main() -> int:
    sys.stdout.reconfigure(newline="\n")  # LF on every platform
    values = vectors()
    text = render(values)
    if "--check" in sys.argv[1:]:
        with open(CORE_TXT, encoding="utf-8") as f:
            core = dict(
                line.strip().split("=", 1)
                for line in f
                if line.strip() and not line.startswith("#")
            )
        # The old folder key is the one of the core vectors.
        if core["k_fold"] != values["k_fold_old"].hex():
            print("k_fold differs from crates/core/tests/vectors/sync_kat.txt")
            return 1
        with open(OUT_TXT, encoding="utf-8", newline="") as f:
            current = f.read().replace("\r\n", "\n")
        if current != text:
            print("sync_kat.txt is stale: regenerate it with this script")
            return 1
        print("ok")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
